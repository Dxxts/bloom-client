	public static final int SIZE = 9;
	/** Per row: x0, x1, x0, x1, ... (end exclusive). */
	private final int[][] runs;
	/** The same icon upscaled 2× with Scale2x, which smooths diagonals; used when drawing at physical resolution. */
	private final int[][] runs2;

	Icon(String... rows) {
		boolean[][] px = new boolean[rows.length][SIZE];
		for (int y = 0; y < rows.length; y++) {
			for (int x = 0; x < SIZE && x < rows[y].length(); x++) px[y][x] = rows[y].charAt(x) == '#';
		}
		runs = toRuns(px);
		runs2 = toRuns(scale2x(px));
	}

	private static int[][] toRuns(boolean[][] px) {
		int[][] out = new int[px.length][];
		for (int y = 0; y < px.length; y++) {
			boolean[] row = px[y];
			int[] buf = new int[row.length + 1];
			int n = 0;
			for (int x = 0; x < row.length; ) {
				if (!row[x]) {
					x++;
					continue;
				}
				int start = x;
				while (x < row.length && row[x]) x++;
				buf[n++] = start;
				buf[n++] = x;
			}
			out[y] = java.util.Arrays.copyOf(buf, n);
		}
		return out;
	}

	/** Scale2x (EPX): each pixel becomes 2×2, corners follow matching neighbours so diagonals stay thin and smooth. */
	private static boolean[][] scale2x(boolean[][] src) {
		int h = src.length, w = src[0].length;
		boolean[][] dst = new boolean[h * 2][w * 2];
		for (int y = 0; y < h; y++) {
			for (int x = 0; x < w; x++) {
				boolean p = src[y][x];
				boolean a = y > 0 && src[y - 1][x], b = x < w - 1 && src[y][x + 1];
				boolean c = x > 0 && src[y][x - 1], d = y < h - 1 && src[y + 1][x];
				boolean e0 = p, e1 = p, e2 = p, e3 = p;
				if (b != c && a != d) {
					e0 = c == a ? c : p;
					e1 = a == b ? b : p;
					e2 = c == d ? c : p;
					e3 = d == b ? b : p;
				}
				dst[y * 2][x * 2] = e0;
				dst[y * 2][x * 2 + 1] = e1;
				dst[y * 2 + 1][x * 2] = e2;
				dst[y * 2 + 1][x * 2 + 1] = e3;
			}
		}
		return dst;
	}

	/** Draws the icon with its top-left corner at (x, y), one icon pixel = {@code scale} units. */
	public void draw(GuiGraphicsExtractor g, int x, int y, int scale, int color) {
		if ((color >>> 24) == 0) return;
		int fine = Draw.fine();
		if (fine >= 2) {
			// Physical-pixel drawing: the 18×18 Scale2x grid, each cell (fine × scale) / 2 pixels.
			int s = fine * scale;
			g.pose().pushMatrix();
			g.pose().scale(1f / fine, 1f / fine);
			int ox = x * fine, oy = y * fine;
			for (int row = 0; row < runs2.length; ) {
				int[] r = runs2[row];
				// Merge identical consecutive rows (Scale2x output often repeats) into one fill.
				int end = row + 1;
				while (end < runs2.length && java.util.Arrays.equals(runs2[end], r)) end++;
				int y0 = oy + row * s / 2, y1 = oy + end * s / 2;
				if (y1 > y0) {
					for (int i = 0; i < r.length; i += 2) {
						g.fill(ox + r[i] * s / 2, y0, ox + r[i + 1] * s / 2, y1, color);
					}
				}
				row = end;
			}
			g.pose().popMatrix();
			return;
		}
		for (int row = 0; row < runs.length; row++) {
			int[] r = runs[row];
			for (int i = 0; i < r.length; i += 2) {
				g.fill(x + r[i] * scale, y + row * scale, x + r[i + 1] * scale, y + (row + 1) * scale, color);
			}
		}
	}

	public void draw(GuiGraphicsExtractor g, int x, int y, int color) {
		draw(g, x, y, 1, color);
	}
